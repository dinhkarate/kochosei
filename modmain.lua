    function self:SetCharacter(hero)
        _oldSetCharacter(self, hero)

        if hero == "wurt" then
            -- Luôn hiện bị khóa
            self.image:SetTint(0.5, 0.5, 0.5, 1)
            self.head_animstate:SetMultColour(0.5, 0.5, 0.5, 1)
            self.lock_img:Show()

            -- Gắn lại sự kiện click -> hiện popup
            self:SetOnClick(function()
                TheFrontEnd:PushScreen(PopupDialogScreen(
                    STRINGS.UI.LOBBYSCREEN.TITLE,
                    "Nhân vật này đã bị ban chỉ vì nó có lông màu xanh thôi.",
                    {
                        { text = "The F, * gì thế?", cb = function() TheFrontEnd:PopScreen() end }
                    }
                ))
            end)
        end
    end
end)

