    if key_handlers[name] then
        key_handlers[name]:Remove()
        key_handlers[name] = nil
    end
    if key and handler_fns[name] then
        key_handlers[name] = GLOBAL.TheInput:AddKeyDownHandler(key,
                                                               handler_fns[name])
    end
end

